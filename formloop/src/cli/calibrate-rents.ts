// One-off: source median rents per area from You.com results, extracted by the normalizer model.
// One search + one model call per area. Writes research/rent_calibration.yaml (areas with nothing sourced are omitted).
// Numbers are kept only if the model cites at least one result for them and they fall in $1,000-$10,000.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { stringify } from 'yaml';
import { chatJSON, usageLog, usageSummary } from '../crusoe.ts';
import { researchDir } from '../research.ts';
import { ydcCacheDir, ydcSearch } from '../ydc.ts';

const AREAS: Array<[string, string]> = [
	['mission', 'Mission'], ['soma', 'SoMa'], ['hayes_valley', 'Hayes Valley'], ['nob_hill', 'Nob Hill'],
	['pacific_heights', 'Pacific Heights'], ['marina', 'Marina'], ['inner_sunset', 'Inner Sunset'],
	['outer_sunset', 'Outer Sunset'], ['inner_richmond', 'Inner Richmond'], ['outer_richmond', 'Outer Richmond'],
	['noe_valley', 'Noe Valley'], ['castro', 'Castro'], ['bernal_heights', 'Bernal Heights'],
	['potrero_hill', 'Potrero Hill'], ['dogpatch', 'Dogpatch'], ['tenderloin', 'Tenderloin'],
	['north_beach', 'North Beach'], ['russian_hill', 'Russian Hill'], ['lower_haight', 'Lower Haight'],
	['excelsior', 'Excelsior'], ['oakland', 'Oakland'], ['berkeley_east_bay', 'Berkeley / East Bay'],
	['marin', 'Marin'], ['peninsula', 'Peninsula']
];
const REGIONS: Record<string, string> = {
	oakland: 'Oakland California',
	berkeley_east_bay: 'Berkeley California',
	marin: 'Marin County California',
	peninsula: 'San Mateo County Peninsula California'
};
const FIELDS = ['studio', 'one_br', 'two_br'] as const;

type Extract = {
	studio?: number | null; one_br?: number | null; two_br?: number | null; yoy_pct?: number | null;
	cited?: Record<string, number[]> | number[];
};

const system = `You extract apartment rent figures from numbered web search results.
Use ONLY numbers stated in the results. Never estimate, average, or infer. If a figure is not stated for the named area, use null.
Return JSON: {"studio": number|null, "one_br": number|null, "two_br": number|null, "yoy_pct": number|null,
"cited": {"studio": [result numbers], "one_br": [...], "two_br": [...], "yoy_pct": [...]}}
studio/one_br/two_br = monthly USD median or typical asking rent. yoy_pct = year-over-year rent change in percent (e.g. 3.5 or -2).
Only report figures for the named area itself, not the whole city or a different neighborhood.`;

const cacheCount = () => (existsSync(ydcCacheDir) ? readdirSync(ydcCacheDir).length : 0);
const before = cacheCount();
const out: Record<string, Record<string, unknown>> = {};
let searches = 0;

for (const [id, name] of AREAS) {
	const place = REGIONS[id] ?? `${name} San Francisco`;
	const query = `${place} median rent studio 1 bedroom 2 bedroom 2026`;
	let results;
	try {
		results = await ydcSearch(query, { count: 5 });
		searches++;
	} catch (e) {
		console.warn(`${id}: search failed: ${(e as Error).message}`);
		continue;
	}
	if (!results?.length) {
		console.warn(`${id}: no results`);
		continue;
	}
	const numbered = results
		.map((r, i) => `[${i + 1}] ${r.title}\n${r.url}\n${r.description}\n${r.snippets.join('\n')}`)
		.join('\n\n');
	let data: Extract;
	try {
		({ data } = await chatJSON<Extract>('normalizer', system, `Area: ${name}\n\nResults:\n${numbered}`, { maxTokens: 600 }));
	} catch (e) {
		console.warn(`${id}: model call failed: ${(e as Error).message}`);
		continue;
	}
	const citedFor = (f: string): number[] => {
		const c = data.cited;
		const list = Array.isArray(c) ? c : (c?.[f] ?? []);
		return list.filter((n) => Number.isInteger(n) && n >= 1 && n <= results.length);
	};
	const entry: Record<string, unknown> = {};
	const urls = new Set<string>();
	for (const f of FIELDS) {
		const v = data[f];
		const cites = citedFor(f);
		if (typeof v === 'number' && Number.isFinite(v) && v >= 1000 && v <= 10000 && cites.length) {
			entry[f] = Math.round(v);
			for (const n of cites) urls.add(results[n - 1].url);
		}
	}
	const yoy = data.yoy_pct;
	const yoyCites = citedFor('yoy_pct');
	if (typeof yoy === 'number' && Number.isFinite(yoy) && Math.abs(yoy) <= 30 && yoyCites.length) {
		entry.yoy_pct = Math.round(yoy * 10) / 10;
		for (const n of yoyCites) urls.add(results[n - 1].url);
	}
	if (urls.size) {
		entry.sources = [...urls];
		out[id] = entry;
		console.log(`${id}: ${Object.keys(entry).filter((k) => k !== 'sources').join(', ')}`);
	} else console.log(`${id}: nothing sourced`);
}

const header = `# Rent calibration: SOURCED median/typical asking rents per area, from You.com search results.
# Generated by formloop/src/cli/calibrate-rents.ts (npm run calibrate-rents). Editable by the researcher:
# fix or delete any figure; every kept figure must keep at least one source URL.
# Every value here is sourced (cited by a search result); areas or fields missing here fall back to the
# simulated figures in research/market.yaml.
`;
const doc = {
	fetched_at: new Date().toISOString(),
	method: 'One You.com search per area; normalizer model extracts only stated figures from the numbered results, cited; kept if cited and $1,000-$10,000.',
	areas: out
};
writeFileSync(join(researchDir, 'rent_calibration.yaml'), header + stringify(doc));
const newSearches = cacheCount() - before;
console.log(`areas sourced: ${Object.keys(out).length}/${AREAS.length}`);
console.log(`You.com: ${searches} searches, ${newSearches} hit the network (~$${(newSearches * 0.005).toFixed(3)} at $0.005/search)`);
console.log(usageSummary());
console.log(`model cost: $${usageLog.reduce((a, u) => a + u.cost, 0).toFixed(4)}`);
